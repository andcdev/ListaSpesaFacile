def main():
    root = os.path.join(os.path.dirname(__file__), '..', 'lib', 'l10n')
    os.makedirs(root, exist_ok=True)
    for i, lang in enumerate(LANGS):
        arb = {'@@locale': lang}
        for key, entry in S.items():
            arb[key] = entry[i]
            placeholders = entry[5] if len(entry) > 5 else {}
            used = set(re.findall(r'\{(\w+)[},]', entry[i]))
            assert used <= set(placeholders), (lang, key, used)
            if lang == 'it' and placeholders:
                arb['@' + key] = {'placeholders': {name: {'type': t} for name, t in placeholders.items()}}
        with open(os.path.join(root, f'app_{lang}.arb'), 'w', encoding='utf-8') as f:
            json.dump(arb, f, ensure_ascii=False, indent=2)
            f.write('\n')
    print(f'{len(S)} testi in {len(LANGS)} lingue')


if __name__ == '__main__':
    main()
